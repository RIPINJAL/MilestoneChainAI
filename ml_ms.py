import joblib

def predict_risk(duration, intensity):
    # Load the model and scaler
    model = joblib.load("risk_model.pkl")
    scaler = joblib.load("scaler.pkl")

    # Scale the input features using the loaded scaler
    # The scaler expects a 2D array, so we wrap the inputs in a list
    scaled_features = scaler.transform([[duration, intensity]])

    # Make a prediction
    # model.predict returns an array, so we take the first element
    prediction = model.predict(scaled_features)[0]

    # Return the prediction (0 for low risk, 1 for high risk)
    return prediction

